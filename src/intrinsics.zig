//! Intrinsic procedures, modules, statements and keywords (port of
//! `fortls.parsers.internal.intrinsics`). The tables are the constants in
//! `data/`; the procedure documentation is embedded Markdown.

const std = @import("std");
const Allocator = std.mem.Allocator;
const str = @import("str.zig");
const helpers = @import("helpers.zig");
const objects = @import("objects.zig");
const Obj = objects.Obj;
const Ast = objects.Ast;
const C = @import("constants.zig");
const schema = @import("data/schema.zig");
const statements = @import("data/statements.zig");
const keywords = @import("data/keywords.zig");
const procedures = @import("data/procedures.zig");
const modules = @import("data/modules.zig");

/// `itype` of the statement and keyword objects
const statement_itype = C.statement_itype;
const keyword_itype = C.keyword_itype;

/// Markdown documentation of intrinsic procedures, generated by build.zig
/// from `src/data/intrinsics/NAME.md`
const intrinsic_docs = @import("intrinsic_docs");

fn markdownDoc(name: []const u8) ?[]const u8 {
    for (intrinsic_docs.docs) |d| if (std.mem.eql(u8, d.name, name)) return d.markdown;
    return null;
}

pub const Intrinsics = struct {
    /// The documentation of a statement or attribute keyword, and its name as
    /// documented (`ALLOCATE`, `INTENT`)
    /// `arg`: what the parentheses after the word hold (`in` of
    /// `intent(in)`), which tells the variants apart
    pub fn keywordDoc(self: *const Intrinsics, a: std.mem.Allocator, word: []const u8, arg: ?[]const u8) !?struct { name: []const u8, doc: []const u8 } {
        _ = self;
        const tables = .{ &statements.int_stmnts, &statements.var_def, &keywords.var_def, &keywords.arg, &keywords.type_mem, &keywords.vis, &keywords.param };
        if (arg) |x| {
            const full = try std.fmt.allocPrint(a, "{s}({s})", .{ word, std.mem.trim(u8, x, " ") });
            inline for (tables) |t| for (t) |k| {
                const doc = k.doc orelse continue;
                if (std.ascii.eqlIgnoreCase(k.name, full)) return .{ .name = k.name, .doc = doc };
            };
        }
        inline for (tables) |t| for (t) |k| {
            const doc = k.doc orelse continue;
            // `DIMENSION(:)`, `INTENT(IN)`: the word before the parenthesis
            const base = if (std.mem.indexOfScalar(u8, k.name, '(')) |p| k.name[0..p] else k.name;
            if (std.ascii.eqlIgnoreCase(base, word)) return .{ .name = base, .doc = doc };
        };
        return null;
    }

    ast: *Ast,
    stmt_var_def: []*Obj,
    stmt_int_stmnts: []*Obj,
    kw_var_def: []*Obj,
    kw_arg: []*Obj,
    kw_type_mem: []*Obj,
    kw_vis: []*Obj,
    kw_param: []*Obj,
    funs: []*Obj,
    mods: []*Obj,

    pub fn deinit(self: *Intrinsics) void {
        self.ast.destroy();
    }

    /// Port of `get_intrinsic_keywords`
    pub fn keywordsFor(self: *const Intrinsics, a: Allocator, context: i32) ![]*Obj {
        var out: std.ArrayList(*Obj) = .empty;
        switch (context) {
            0 => {
                try out.appendSlice(a, self.stmt_int_stmnts);
                try out.appendSlice(a, self.stmt_var_def);
                try out.appendSlice(a, self.kw_vis);
            },
            1 => {
                try out.appendSlice(a, self.kw_var_def);
                try out.appendSlice(a, self.kw_vis);
                try out.appendSlice(a, self.kw_param);
            },
            2 => {
                try out.appendSlice(a, self.kw_var_def);
                try out.appendSlice(a, self.kw_arg);
                try out.appendSlice(a, self.kw_param);
            },
            3 => {
                try out.appendSlice(a, self.kw_var_def);
                try out.appendSlice(a, self.kw_type_mem);
                try out.appendSlice(a, self.kw_vis);
            },
            else => {
                try out.appendSlice(a, self.kw_var_def);
                try out.appendSlice(a, self.kw_param);
            },
        }
        return out.items;
    }
};

const Loader = struct {
    a: Allocator,
    ast: *Ast,
    lowercase: bool,

    fn case(l: *Loader, s: []const u8) ![]const u8 {
        return if (l.lowercase) try std.ascii.allocLowerString(l.a, s) else s;
    }

    fn keywordObjects(l: *Loader, entries: []const schema.Keyword, itype: C.TypeId) ![]*Obj {
        const out = try l.a.alloc(*Obj, entries.len);
        for (entries, out) |e, *o| {
            o.* = try Obj.newIntrinsic(l.ast, try l.case(e.name), itype, e.doc, try l.case(e.args));
        }
        return out;
    }

    fn procedureObjects(l: *Loader, entries: []const schema.Procedure) ![]*Obj {
        const out = try l.a.alloc(*Obj, entries.len);
        for (entries, out) |e, *o| {
            const itype = switch (e.kind) {
                .subroutine => C.TypeId.subroutine,
                .function => C.TypeId.function,
            };
            const doc = markdownDoc(e.name) orelse e.doc;
            o.* = try Obj.newIntrinsic(l.ast, try l.case(e.name), itype, doc, try l.case(e.args));
        }
        return out;
    }

    fn createModule(l: *Loader, m: schema.Module) !*Obj {
        l.ast.enc_scope_name = null;
        const obj = try Obj.newScope(l.ast, .module, 0, try l.case(m.name), &.{});
        if (m.use) |u| {
            const use = try objects.UseStmt.init(l.ast.allocator(), u, &.{}, &.{});
            try obj.scopeData().use.append(l.ast.allocator(), use);
        }
        for (m.members) |member| try l.addMember(obj, member);
        return obj;
    }

    fn addMember(l: *Loader, parent: *Obj, m: schema.Member) !void {
        const obj = try l.createMember(m, parent);
        try parent.addChild(obj);
        for (m.children) |child| try l.addMember(obj, child);
    }

    fn createMember(l: *Loader, m: schema.Member, enc: *Obj) !*Obj {
        l.ast.enc_scope_name = enc.fqsn;
        const mk = try helpers.mapKeywords(l.a, m.mods, true);
        const name = try l.case(m.name);
        const args = try l.case(m.args);
        return switch (m.kind) {
            .subroutine => Obj.newSubroutine(l.ast, 0, name, args, false, &.{}),
            .function => Obj.newFunction(l.ast, 0, name, .{
                .args = args,
                .result_type = m.return_type,
                .keywords = mk.ids,
            }),
            .variable => Obj.newVariable(l.ast, 0, name, m.desc, mk.ids, .{ .keyword_info = mk.info }),
            .type => Obj.newScope(l.ast, .type, 0, name, mk.ids),
        };
    }
};

/// Load all intrinsics into a new AST arena. Keywords are always sorted.
pub fn load(gpa: Allocator, lowercase: bool) !Intrinsics {
    const ast = try Ast.create(gpa, null);
    errdefer ast.destroy();
    const a = ast.allocator();

    var l: Loader = .{ .a = a, .ast = ast, .lowercase = lowercase };

    const mods = try a.alloc(*Obj, modules.all.len);
    for (modules.all, mods) |m, *o| o.* = try l.createModule(m);
    ast.enc_scope_name = null;

    return .{
        .ast = ast,
        .stmt_var_def = try l.keywordObjects(&statements.var_def, statement_itype),
        .stmt_int_stmnts = try l.keywordObjects(&statements.int_stmnts, statement_itype),
        .kw_var_def = try l.keywordObjects(&keywords.var_def, keyword_itype),
        .kw_arg = try l.keywordObjects(&keywords.arg, keyword_itype),
        .kw_type_mem = try l.keywordObjects(&keywords.type_mem, keyword_itype),
        .kw_vis = try l.keywordObjects(&keywords.vis, keyword_itype),
        .kw_param = try l.keywordObjects(&keywords.param, keyword_itype),
        .funs = try l.procedureObjects(&procedures.all),
        .mods = mods,
    };
}

fn expectSortedByName(table: anytype) !void {
    for (table[1..], 0..) |e, i| {
        try std.testing.expect(std.mem.order(u8, table[i].name, e.name) == .lt);
    }
}

test "intrinsic tables are sorted by name" {
    try expectSortedByName(&procedures.all);
    inline for (.{ "var_def", "int_stmnts" }) |g| try expectSortedByName(&@field(statements, g));
    inline for (.{ "var_def", "arg", "type_mem", "vis", "param" }) |g| try expectSortedByName(&@field(keywords, g));
}

test "load intrinsics" {
    @import("patterns.zig").init();
    var intr = try load(std.testing.allocator, false);
    defer intr.deinit();
    try std.testing.expect(intr.funs.len > 100);
    try std.testing.expectEqualStrings("ABORT", intr.funs[0].name);
    try std.testing.expect(intr.mods.len > 3);
}

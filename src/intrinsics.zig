//! Intrinsic procedures, modules, statements and keywords (port of
//! `fortls.parsers.internal.intrinsics`). The data files are embedded.

const std = @import("std");
const Allocator = std.mem.Allocator;
const str = @import("str.zig");
const json = @import("json.zig");
const helpers = @import("helpers.zig");
const objects = @import("objects.zig");
const Obj = objects.Obj;
const Ast = objects.Ast;

const statements_json = @embedFile("data/statements.json");
const keywords_json = @embedFile("data/keywords.json");
const procedures_json = @embedFile("data/intrinsic.procedures.json");
/// Markdown documentation of intrinsic procedures, generated by build.zig
/// from `src/data/intrinsics/NAME.md`
const intrinsic_docs = @import("intrinsic_docs");

fn markdownDoc(name: []const u8) ?[]const u8 {
    for (intrinsic_docs.docs) |d| if (std.mem.eql(u8, d.name, name)) return d.markdown;
    return null;
}
const modules_json = @embedFile("data/intrinsic.modules.json");

pub const Intrinsics = struct {
    ast: *Ast,
    stmt_var_def: []*Obj,
    stmt_int_stmnts: []*Obj,
    kw_var_def: []*Obj,
    kw_arg: []*Obj,
    kw_type_mem: []*Obj,
    kw_vis: []*Obj,
    kw_param: []*Obj,
    funs: []*Obj,
    mods: []*Obj,

    pub fn deinit(self: *Intrinsics) void {
        self.ast.destroy();
    }

    /// Port of `get_intrinsic_keywords`
    pub fn keywordsFor(self: *const Intrinsics, a: Allocator, context: i32) ![]*Obj {
        var out: std.ArrayList(*Obj) = .empty;
        switch (context) {
            0 => {
                try out.appendSlice(a, self.stmt_int_stmnts);
                try out.appendSlice(a, self.stmt_var_def);
                try out.appendSlice(a, self.kw_vis);
            },
            1 => {
                try out.appendSlice(a, self.kw_var_def);
                try out.appendSlice(a, self.kw_vis);
                try out.appendSlice(a, self.kw_param);
            },
            2 => {
                try out.appendSlice(a, self.kw_var_def);
                try out.appendSlice(a, self.kw_arg);
                try out.appendSlice(a, self.kw_param);
            },
            3 => {
                try out.appendSlice(a, self.kw_var_def);
                try out.appendSlice(a, self.kw_type_mem);
                try out.appendSlice(a, self.kw_vis);
            },
            else => {
                try out.appendSlice(a, self.kw_var_def);
                try out.appendSlice(a, self.kw_param);
            },
        }
        return out.items;
    }
};

const Loader = struct {
    a: Allocator,
    ast: *Ast,
    lowercase: bool,

    fn case(l: *Loader, s: []const u8) ![]const u8 {
        return if (l.lowercase) try str.lower(l.a, s) else s;
    }

    fn intObject(l: *Loader, name: []const u8, obj: json.Value, itype: i32) !*Obj {
        const args = (obj.get("args") orelse json.Value{ .string = "" }).asStr() orelse "";
        const doc = if (obj.get("doc")) |d| d.asStr() else null;
        return Obj.newIntrinsic(l.ast, try l.case(name), itype, doc, try l.case(args));
    }

    /// Sorted (by key) list of intrinsic objects from a JSON object
    fn sortedObjects(l: *Loader, obj: json.Value, itype: i32, use_md: bool) ![]*Obj {
        const entries = obj.object.entries.items;
        const sorted = try l.a.dupe(json.Entry, entries);
        std.mem.sort(json.Entry, sorted, {}, struct {
            fn lt(_: void, x: json.Entry, y: json.Entry) bool {
                return std.mem.order(u8, x.key, y.key) == .lt;
            }
        }.lt);
        var out: std.ArrayList(*Obj) = .empty;
        for (sorted) |e| {
            var v = e.value;
            var t = itype;
            if (use_md) {
                if (markdownDoc(e.key)) |doc| try json.put(l.a, &v, "doc", json.string(doc));
                t = @intCast((v.get("type") orelse json.Value{ .int = 0 }).asInt() orelse 0);
            }
            try out.append(l.a, try l.intObject(e.key, v, t));
        }
        return out.items;
    }

    fn createObject(l: *Loader, obj: json.Value, enc: ?*Obj) !*Obj {
        l.ast.enc_scope_name = if (enc) |e| e.fqsn else null;
        var mk: helpers.MappedKeywords = .{ .ids = &.{}, .info = .{} };
        if (obj.get("mods")) |mods| {
            var list: std.ArrayList([]const u8) = .empty;
            for (mods.items()) |m| try list.append(l.a, m.asStr() orelse "");
            mk = try helpers.mapKeywords(l.a, list.items);
        }
        const name = try l.case(obj.get("name").?.asStr().?);
        const args = try l.case((obj.get("args") orelse json.Value{ .string = "" }).asStr() orelse "");
        const t = obj.get("type").?.asInt().?;
        switch (t) {
            0 => {
                const m = try Obj.newScope(l.ast, .module, 0, name, &.{});
                if (obj.get("use")) |u| {
                    const use = try objects.UseStmt.init(l.ast.allocator(), u.asStr().?, &.{}, &.{});
                    try m.use.append(l.ast.allocator(), use);
                }
                return m;
            },
            1 => return Obj.newSubroutine(l.ast, 0, name, args, false, &.{}),
            2 => return Obj.newFunction(l.ast, 0, name, .{
                .args = args,
                .result_type = obj.get("return").?.asStr(),
                .keywords = mk.ids,
            }),
            3 => return Obj.newVariable(l.ast, 0, name, obj.get("desc").?.asStr().?, mk.ids, .{ .keyword_info = mk.info }),
            4 => return Obj.newScope(l.ast, .type, 0, name, mk.ids),
            else => return error.InvalidIntrinsic,
        }
    }

    fn addChildren(l: *Loader, obj: json.Value, fort_obj: *Obj) !void {
        const children = obj.get("children") orelse return;
        for (children.items()) |child| {
            const child_obj = try l.createObject(child, fort_obj);
            try fort_obj.addChild(child_obj);
            try l.addChildren(child, child_obj);
        }
    }
};

/// Load all intrinsics into a new AST arena. Keywords are always sorted.
pub fn load(gpa: Allocator, lowercase: bool) !Intrinsics {
    const ast = try Ast.create(gpa, null);
    errdefer ast.destroy();
    const a = ast.allocator();
    const saved_sort = helpers.sort_keywords;
    helpers.sort_keywords = true;
    defer helpers.sort_keywords = saved_sort;

    var l: Loader = .{ .a = a, .ast = ast, .lowercase = lowercase };
    const stmts = try json.parse(a, statements_json);
    const kws = try json.parse(a, keywords_json);
    const procs = try json.parse(a, procedures_json);
    const mods = try json.parse(a, modules_json);

    var mod_list: std.ArrayList(*Obj) = .empty;
    for (mods.object.entries.items) |e| {
        const fort_obj = try l.createObject(e.value, null);
        try l.addChildren(e.value, fort_obj);
        try mod_list.append(a, fort_obj);
    }
    ast.enc_scope_name = null;

    return .{
        .ast = ast,
        .stmt_var_def = try l.sortedObjects(stmts.get("var_def").?, 15, false),
        .stmt_int_stmnts = try l.sortedObjects(stmts.get("int_stmnts").?, 15, false),
        .kw_var_def = try l.sortedObjects(kws.get("var_def").?, 14, false),
        .kw_arg = try l.sortedObjects(kws.get("arg").?, 14, false),
        .kw_type_mem = try l.sortedObjects(kws.get("type_mem").?, 14, false),
        .kw_vis = try l.sortedObjects(kws.get("vis").?, 14, false),
        .kw_param = try l.sortedObjects(kws.get("param").?, 14, false),
        .funs = try l.sortedObjects(procs, 0, true),
        .mods = mod_list.items,
    };
}

test "load intrinsics" {
    @import("patterns.zig").init();
    var intr = try load(std.testing.allocator, false);
    defer intr.deinit();
    try std.testing.expect(intr.funs.len > 100);
    try std.testing.expectEqualStrings("ABORT", intr.funs[0].name);
    try std.testing.expect(intr.mods.len > 3);
}

//! Build-time generator of the `intrinsic_docs` module: the Markdown pages
//! of the M_intrinsics package (`md3/NAME.md`, one per intrinsic procedure),
//! as upstream wrote them except for their links to each other.
//!
//! Upstream links its pages to each other by name (`[**sign**(3)](#sign)`,
//! a few `(cos)`), which leads nowhere in a hover. Each such link is pointed
//! at the page upstream publishes for the procedure; a name without a
//! published page keeps only its text.
//!
//! Usage: intrinsic_docs MD_DIR HTML_DIR OUT_DIR
//! (`md3` and `docs` of the package; OUT_DIR receives the pages and
//! `intrinsic_docs.zig`, which embeds them)

const std = @import("std");
const Io = std.Io;
const Allocator = std.mem.Allocator;

/// Where upstream publishes the pages (`docs/NAME.3fortran.html`)
const pages_url = "https://urbanjost.github.io/M_intrinsics/";
const page_suffix = ".3fortran.html";

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const a = init.arena.allocator();
    const argv = try init.minimal.args.toSlice(a);
    if (argv.len != 4) {
        std.log.err("usage: intrinsic_docs MD_DIR HTML_DIR OUT_DIR", .{});
        std.process.exit(2);
    }
    const cwd = Io.Dir.cwd();

    var pages: std.StringHashMapUnmanaged(void) = .empty;
    for (try listFiles(io, a, argv[2], page_suffix)) |name| try pages.put(a, name, {});

    const names = try listFiles(io, a, argv[1], ".md");
    var md_dir = try cwd.openDir(io, argv[1], .{});
    defer md_dir.close(io);
    var out_dir = try cwd.openDir(io, argv[3], .{});
    defer out_dir.close(io);

    var index: std.Io.Writer.Allocating = .init(a);
    const w = &index.writer;
    try w.writeAll(
        \\//! Generated by build/intrinsic_docs.zig from the M_intrinsics package
        \\pub const Doc = struct { name: []const u8, markdown: []const u8 };
        \\pub const docs = [_]Doc{
        \\
    );
    for (names) |name| {
        const file = try std.fmt.allocPrint(a, "{s}.md", .{name});
        const text = try md_dir.readFileAlloc(io, file, a, .limited(1 << 20));
        try out_dir.writeFile(io, .{ .sub_path = file, .data = try fixLinks(a, text, &pages) });
        try w.print("    .{{ .name = \"{s}\", .markdown = @embedFile(\"{s}\") }},\n", .{ name, file });
    }
    try w.writeAll("};\n");
    try out_dir.writeFile(io, .{ .sub_path = "intrinsic_docs.zig", .data = index.written() });
}

/// Stems of the files of `dir_path` named `*suffix`, sorted (upstream's
/// directories also hold editor files and subdirectories)
fn listFiles(io: Io, a: Allocator, dir_path: []const u8, suffix: []const u8) ![][]const u8 {
    var dir = try Io.Dir.cwd().openDir(io, dir_path, .{ .iterate = true });
    defer dir.close(io);
    var out: std.ArrayList([]const u8) = .empty;
    var it = dir.iterate();
    while (try it.next(io)) |e| {
        if (e.kind != .file or e.name.len <= suffix.len or !std.mem.endsWith(u8, e.name, suffix)) continue;
        try out.append(a, try a.dupe(u8, e.name[0 .. e.name.len - suffix.len]));
    }
    std.mem.sort([]const u8, out.items, {}, struct {
        fn lt(_: void, x: []const u8, y: []const u8) bool {
            return std.mem.order(u8, x, y) == .lt;
        }
    }.lt);
    return out.items;
}

/// `text` with its links to other pages pointed at the published pages
/// (`pages`: the names that have one); code is left alone
fn fixLinks(a: Allocator, text: []const u8, pages: *const std.StringHashMapUnmanaged(void)) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    var fence: ?[]const u8 = null;
    var lines = std.mem.splitScalar(u8, text, '\n');
    var first = true;
    while (lines.next()) |line| {
        if (!first) try out.append(a, '\n');
        first = false;
        if (fenceMarker(line)) |m| {
            if (fence) |open| {
                if (m[0] == open[0] and m.len >= open.len) fence = null;
            } else fence = m;
            try out.appendSlice(a, line);
            continue;
        }
        if (fence != null) {
            try out.appendSlice(a, line);
            continue;
        }
        try fixLine(a, &out, line, pages);
    }
    return out.items;
}

/// The backticks or tildes opening or closing a fenced code block
fn fenceMarker(line: []const u8) ?[]const u8 {
    const s = std.mem.trimStart(u8, line, " ");
    if (line.len - s.len > 3 or s.len < 3 or (s[0] != '`' and s[0] != '~')) return null;
    var n: usize = 0;
    while (n < s.len and s[n] == s[0]) n += 1;
    return if (n >= 3) s[0..n] else null;
}

fn fixLine(a: Allocator, out: *std.ArrayList(u8), line: []const u8, pages: *const std.StringHashMapUnmanaged(void)) !void {
    var i: usize = 0;
    while (i < line.len) {
        switch (line[i]) {
            '\\' => {
                const n = @min(2, line.len - i);
                try out.appendSlice(a, line[i .. i + n]);
                i += n;
            },
            // a code span: copied up to the closing run of as many backticks
            '`' => {
                var n: usize = 0;
                while (i + n < line.len and line[i + n] == '`') n += 1;
                const end = if (std.mem.indexOf(u8, line[i + n ..], line[i .. i + n])) |e| i + n + e + n else i + n;
                try out.appendSlice(a, line[i..end]);
                i = end;
            },
            '[' => if (link(line, i)) |l| {
                if (pageName(a, l, pages)) |name| {
                    try out.print(a, "[{s}]({s}{s}{s})", .{ l.text, pages_url, name, page_suffix });
                } else if (isPageRef(l.target)) {
                    try out.appendSlice(a, l.text);
                } else {
                    try out.appendSlice(a, line[i..l.end]);
                }
                i = l.end;
            } else {
                try out.append(a, '[');
                i += 1;
            },
            else => {
                try out.append(a, line[i]);
                i += 1;
            },
        }
    }
}

const Link = struct { text: []const u8, target: []const u8, end: usize };

/// The inline link `[text](target)` starting at `line[start]`
fn link(line: []const u8, start: usize) ?Link {
    var i = start + 1;
    while (i < line.len and line[i] != ']') : (i += 1) {
        if (line[i] == '\\') i += 1 else if (line[i] == '[') return null;
    }
    if (i + 1 >= line.len or line[i + 1] != '(') return null;
    const close = std.mem.indexOfScalarPos(u8, line, i + 2, ')') orelse return null;
    const target = line[i + 2 .. close];
    if (target.len == 0 or std.mem.indexOfAny(u8, target, " \t") != null) return null;
    return .{ .text = line[start + 1 .. i], .target = target, .end = close + 1 };
}

/// A link to another page by name (`#sign`, `cos`), not to a URL or file
fn isPageRef(target: []const u8) bool {
    return std.mem.indexOfAny(u8, target, ":/.") == null;
}

/// The published page of a link to another page: of the procedure its text
/// names (`**acos**(3)`), else of its target (upstream's `[**acos**(3)](cos)`
/// and `[**co\_lbound**(3)](lcobound)` do not agree)
fn pageName(a: Allocator, l: Link, pages: *const std.StringHashMapUnmanaged(void)) ?[]const u8 {
    if (!isPageRef(l.target)) return null;
    var text: std.ArrayList(u8) = .empty;
    for (l.text) |c| switch (c) {
        '*', '\\' => {},
        '(' => break,
        else => text.append(a, std.ascii.toLower(c)) catch return null,
    };
    if (pages.contains(text.items)) return text.items;
    const name = std.ascii.allocLowerString(a, std.mem.trimStart(u8, l.target, "#")) catch return null;
    return if (pages.contains(name)) name else null;
}

test fixLinks {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var pages: std.StringHashMapUnmanaged(void) = .empty;
    try pages.put(a, "sign", {});
    try pages.put(a, "cos", {});
    try pages.put(a, "acos", {});
    try pages.put(a, "lcobound", {});
    const cases = [_][2][]const u8{
        .{ "[**sign**(3)](#sign)", "[**sign**(3)](https://urbanjost.github.io/M_intrinsics/sign.3fortran.html)" },
        .{ "see [**cos**(3)](cos).", "see [**cos**(3)](https://urbanjost.github.io/M_intrinsics/cos.3fortran.html)." },
        // the procedure the text names, else the target
        .{ "[**acos**(3)](cos)", "[**acos**(3)](https://urbanjost.github.io/M_intrinsics/acos.3fortran.html)" },
        .{ "[**co\\_lbound**(3)](lcobound)", "[**co\\_lbound**(3)](https://urbanjost.github.io/M_intrinsics/lcobound.3fortran.html)" },
        // no published page: the text alone
        .{ "[**tan2**(3)](#tan2), [**co\\_lbound**(3)](#co_lbound)", "**tan2**(3), **co\\_lbound**(3)" },
        // links elsewhere, code and escapes are left alone
        .{ "[Wikipedia](https://en.wikipedia.org/wiki/Sign)", "[Wikipedia](https://en.wikipedia.org/wiki/Sign)" },
        .{ "`a[i](#sign)` and \\[x](#sign)", "`a[i](#sign)` and \\[x](#sign)" },
        .{ "```text\n[s](#sign)\n```\n[s](#sign)", "```text\n[s](#sign)\n```\n[s](https://urbanjost.github.io/M_intrinsics/sign.3fortran.html)" },
    };
    for (cases) |c| try std.testing.expectEqualStrings(c[1], try fixLinks(a, c[0], &pages));
}
